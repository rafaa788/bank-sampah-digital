function getBSUById(id) {
    for (var i = 0; i < dataBSU.length; i++) {
        if (dataBSU[i].id === id) return dataBSU[i];
    }
    return null;
}

function getBSUByUsername(username) {
    if (!username) return null;
    for (var i = 0; i < dataBSU.length; i++) {
        if (dataBSU[i].username && dataBSU[i].username.toLowerCase() === username.toLowerCase()) {
            return dataBSU[i];
        }
    }
    return null;
}

function validateBSULogin(username, password) {
    var bsu = getBSUByUsername(username);
    if (bsu && bsu.password === password) return bsu;
    return null;
}

function getUniqueRW() {
    var rws = [];
    for (var i = 0; i < dataBSU.length; i++) {
        if (dataBSU[i].rw && rws.indexOf(dataBSU[i].rw) === -1) {
            rws.push(dataBSU[i].rw);
        }
    }
    return rws.sort();
}

function getUniqueRT(rw) {
    var rts = [];
    for (var i = 0; i < dataBSU.length; i++) {
        var bsu = dataBSU[i];
        if ((!rw || bsu.rw === rw) && bsu.rt && rts.indexOf(bsu.rt) === -1) {
            if (bsu.rt !== 'all') rts.push(bsu.rt);
        }
    }
    return rts.sort();
}

function getBSUByRW(rw) {
    var result = [];
    for (var i = 0; i < dataBSU.length; i++) {
        if (dataBSU[i].rw === rw) result.push(dataBSU[i]);
    }
    return result;
}

function getBSUByRT(rw, rt) {
    var result = [];
    for (var i = 0; i < dataBSU.length; i++) {
        var bsu = dataBSU[i];
        if (bsu.rw === rw && (bsu.rt === rt || bsu.rt === 'all')) {
            result.push(bsu);
        }
    }
    return result;
}

function getTotalBSU() {
    return dataBSU.length;
}

function getBSUByKeyword(keyword) {
    if (!keyword) return dataBSU;
    var result = [];
    var kw = keyword.toLowerCase();
    for (var i = 0; i < dataBSU.length; i++) {
        var bsu = dataBSU[i];
        if (bsu.nama.toLowerCase().includes(kw) || 
            bsu.rw.toLowerCase().includes(kw) || 
            bsu.rt.toLowerCase().includes(kw) ||
            bsu.ketua.toLowerCase().includes(kw) ||
            bsu.id.toLowerCase().includes(kw)) {
            result.push(bsu);
        }
    }
    return result;
}

